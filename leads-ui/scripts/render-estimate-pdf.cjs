// Renders an estimate PDF in a plain Node process, outside Next's bundler.
// Next bundles React 19 for server code, but @react-pdf/renderer needs React 18,
// so the route spawns this script and exchanges JSON (stdin) for PDF bytes (stdout).
const React = require("react");
const { renderToBuffer, Document, Page, View, Text, Image, StyleSheet } = require("@react-pdf/renderer");

const h = React.createElement;

const styles = StyleSheet.create({
  page: { padding: 32, fontSize: 10, fontFamily: "Helvetica", color: "#1e293b" },
  header: {
    flexDirection: "row",
    justifyContent: "space-between",
    marginBottom: 24,
    paddingBottom: 12,
    borderBottom: "1pt solid #e2e8f0",
  },
  companyName: { fontSize: 16, fontWeight: 700 },
  companyDetail: { fontSize: 9, color: "#64748b" },
  estimateTitle: { fontSize: 14, fontWeight: 700, textAlign: "right" },
  section: { marginBottom: 16 },
  label: { fontSize: 8, color: "#94a3b8", textTransform: "uppercase", marginBottom: 2 },
  value: { fontSize: 10 },
  tableHeaderRow: {
    flexDirection: "row",
    backgroundColor: "#f8fafc",
    paddingVertical: 6,
    paddingHorizontal: 4,
  },
  tableRow: {
    flexDirection: "row",
    paddingVertical: 6,
    paddingHorizontal: 4,
    borderBottom: "1pt solid #f1f5f9",
  },
  colName: { flex: 3 },
  colQty: { flex: 1, textAlign: "right" },
  colLength: { flex: 1, textAlign: "right" },
  colWidth: { flex: 1, textAlign: "right" },
  colArea: { flex: 1.3, textAlign: "right" },
  colRate: { flex: 1.3, textAlign: "right" },
  colTotal: { flex: 1.5, textAlign: "right" },
  headerText: { fontSize: 8, color: "#64748b", textTransform: "uppercase" },
  totalsBlock: { marginTop: 16, alignItems: "flex-end" },
  totalsRow: { flexDirection: "row", width: 200, justifyContent: "space-between", marginBottom: 2 },
  grandTotalRow: {
    flexDirection: "row",
    width: 200,
    justifyContent: "space-between",
    marginTop: 4,
    paddingTop: 4,
    borderTop: "1pt solid #1e293b",
  },
  headerNote: { fontSize: 9, color: "#475569", marginBottom: 16 },
  footer: { marginTop: 32, fontSize: 8, color: "#94a3b8", textAlign: "center" },
});

function money(amount) {
  return new Intl.NumberFormat("en-IN", { style: "currency", currency: "INR", maximumFractionDigits: 2 })
    .format(amount || 0);
}

function estimateDocument({ company, lead, estimate, items }) {
  const contactLine = [company.phone, company.email].filter(Boolean).join(" · ");
  const footerText = company.footer
    || `This estimate is valid for 15 days from the date above. Generated by ${company.name}.`;

  return h(Document, null,
    h(Page, { size: "A4", style: styles.page },
      h(View, { style: styles.header },
        h(View, { style: { flexDirection: "row", gap: 12, flex: 1 } },
          company.logo ? h(Image, { src: company.logo, style: { width: 56, height: 56, objectFit: "contain" } }) : null,
          h(View, null,
            h(Text, { style: styles.companyName }, company.name),
            company.address ? h(Text, { style: styles.companyDetail }, company.address) : null,
            contactLine ? h(Text, { style: styles.companyDetail }, contactLine) : null,
            company.website ? h(Text, { style: styles.companyDetail }, company.website) : null,
            company.tax_id ? h(Text, { style: styles.companyDetail }, `Tax ID: ${company.tax_id}`) : null,
          ),
        ),
        h(View, null,
          h(Text, { style: styles.estimateTitle }, "ESTIMATE"),
          h(Text, { style: styles.companyDetail }, `Version ${estimate.version}`),
          h(Text, { style: styles.companyDetail }, new Date(estimate.created_at).toLocaleDateString()),
        ),
      ),

      company.header ? h(Text, { style: styles.headerNote }, company.header) : null,

      h(View, { style: styles.section },
        h(Text, { style: styles.label }, "Prepared for"),
        h(Text, { style: styles.value }, lead.sender_name || ""),
        h(Text, { style: styles.value }, lead.sender_email || ""),
      ),

      h(View, null,
        h(View, { style: styles.tableHeaderRow },
          h(Text, { style: [styles.colName, styles.headerText] }, "Service"),
          h(Text, { style: [styles.colQty, styles.headerText] }, "Qty"),
          h(Text, { style: [styles.colLength, styles.headerText] }, "Length"),
          h(Text, { style: [styles.colWidth, styles.headerText] }, "Width"),
          h(Text, { style: [styles.colArea, styles.headerText] }, "Area"),
          h(Text, { style: [styles.colRate, styles.headerText] }, "Rate"),
          h(Text, { style: [styles.colTotal, styles.headerText] }, "Amount"),
        ),
        items.map((item) => {
          const isArea = item.pricing_type === "per_sqft" || item.pricing_type === "per_sqinch";
          const isRft = item.pricing_type === "per_rft";
          const unit = item.pricing_type === "per_sqft" ? "sqft" : "sqin";
          return h(View, { style: styles.tableRow, key: item.id },
            h(Text, { style: styles.colName }, item.name || ""),
            h(Text, { style: styles.colQty }, isArea || isRft ? "" : String(item.quantity ?? "")),
            h(Text, { style: styles.colLength }, isArea || isRft ? String(item.length ?? "") : ""),
            h(Text, { style: styles.colWidth }, isArea ? String(item.width ?? "") : ""),
            h(Text, { style: styles.colArea }, isArea ? `${item.computed_area} ${unit}` : ""),
            h(Text, { style: styles.colRate }, money(item.rate_at_time)),
            h(Text, { style: styles.colTotal }, money(item.line_total)),
          );
        }),
      ),

      h(View, { style: styles.totalsBlock },
        h(View, { style: styles.totalsRow }, h(Text, null, "Subtotal"), h(Text, null, money(estimate.subtotal))),
        h(View, { style: styles.totalsRow }, h(Text, null, "Tax"), h(Text, null, money(estimate.tax))),
        h(View, { style: styles.grandTotalRow }, h(Text, null, "Total"), h(Text, null, money(estimate.total))),
      ),

      h(Text, { style: styles.footer }, footerText),
    ),
  );
}

let input = "";
process.stdin.setEncoding("utf8");
process.stdin.on("data", (chunk) => { input += chunk; });
process.stdin.on("end", async () => {
  try {
    const buffer = await renderToBuffer(estimateDocument(JSON.parse(input)));
    process.stdout.write(buffer);
  } catch (err) {
    process.stderr.write(err.stack || String(err));
    process.exit(1);
  }
});
